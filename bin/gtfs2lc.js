#!/usr/bin/env node

const { Command, InvalidArgumentError, Option } = require("commander");
const fs = require("node:fs");
const { readFile, readdir, rm } = require("node:fs/promises");
const { once } = require("node:events");
const path = require("node:path");
const gtfs2lc = require("../lib/gtfs2lc.js");
const packageJson = require("../package.json");

const program = new Command();

program
  .name("gtfs2lc")
  .description("Convert an extracted GTFS feed to Linked Connections")
  .version(packageJson.version)
  .argument("<path>", "path to the extracted GTFS feed")
  .option(
    "-f, --format <format>",
    "output format: jelly, arrow, csv, ntriples, turtle, json, jsonld, mongo, or mongold",
    "json",
  )
  .option("-b, --base-uris <path>", "JSON file containing URI templates")
  .option(
    "--source-id <key>",
    "arrow: persistent source namespace, e.g. be.sncb",
  )
  .option(
    "--profile <name>",
    "arrow: linked-connections-v2-alpha or irail-cdn-v1",
    "linked-connections-v2-alpha",
  )
  .option("--iri-strategy <path>", "arrow: full JSON identity registry")
  .option("--id-base <iri>", "arrow: stable global identity base")
  .option(
    "--release-id <id>",
    "arrow: immutable release identifier (generated by default)",
  )
  .option(
    "--url-prefix <path>",
    "arrow: origin-relative delivery prefix; irail profile defaults to /data",
  )
  .option(
    "--start-date <date>",
    "arrow: first service day, YYYYMMDD or YYYY-MM-DD",
  )
  .option("--end-date <date>", "arrow: last service day, inclusive")
  .option(
    "--default-transfer-time <seconds>",
    "arrow: fallback transfer buffer",
    parseNonnegativeInteger,
    120,
  )
  .option("--license <iri>", "arrow: source license identifier or URL")
  .addOption(new Option("--baseUris <path>").hideHelp())
  .option("-o, --output <path>", "directory in which to store the result")
  .option(
    "-c, --compressed",
    "keep the resulting connection file gzip-compressed",
  )
  .option(
    "-s, --stream",
    "write the resulting connection file to standard output",
  )
  .option("-S, --store <store>", "LevelStore or MemStore", "MemStore")
  .option("--fresh", "discard historic conversion records")
  .option(
    "--workers <count>",
    "number of conversion workers",
    parsePositiveInteger,
  )
  .option(
    "--regions <count>",
    "arrow format only: geospatially partition connections into this many regions (see arrowconnections.md)",
    parsePositiveInteger,
    1,
  )
  .showHelpAfterError()
  .action(run);

function parsePositiveInteger(value) {
  const parsed = Number.parseInt(value, 10);
  if (!Number.isInteger(parsed) || parsed < 1) {
    throw new InvalidArgumentError("must be a positive integer");
  }
  return parsed;
}

function parseNonnegativeInteger(value) {
  if (!/^\d+$/.test(value) || Number(value) > 0xffffffff) {
    throw new InvalidArgumentError("must be an unsigned 32-bit integer");
  }
  return Number(value);
}

async function run(sourceArgument, options) {
  const sourcePath = path.resolve(sourceArgument);
  const outputPath = path.resolve(options.output || sourcePath);
  const baseUris = options.baseUris
    ? JSON.parse(await readFile(options.baseUris, "utf8"))
    : null;

  const cleanup = async () => {
    const entries = await readdir(outputPath, { withFileTypes: true }).catch(
      () => [],
    );
    const temporary = entries
      .filter(
        (entry) =>
          entry.name.startsWith("raw_") ||
          entry.name.startsWith("connections_"),
      )
      .map((entry) =>
        rm(path.join(outputPath, entry.name), { recursive: true, force: true }),
      );
    await Promise.all(temporary);
  };
  for (const signal of ["SIGINT", "SIGTERM"]) {
    process.once(signal, () => {
      cleanup()
        .catch(console.error)
        .finally(() => process.exit(128 + (signal === "SIGINT" ? 2 : 15)));
    });
  }

  if (options.stream && options.format === "arrow") {
    throw new Error(
      "--stream is not supported for the arrow format: it writes multiple partitioned files, not one stream. Use --output instead.",
    );
  }

  console.error("Converting GTFS to Linked Connections...");
  const mapper = new gtfs2lc.Connections({
    store: options.store,
    format: options.format,
    compressed: options.compressed,
    fresh: options.fresh,
    baseUris,
    workers: options.workers,
    regions: options.regions,
    sourceId: options.sourceId,
    profile: options.profile,
    iriStrategy: options.iriStrategy
      ? JSON.parse(await readFile(options.iriStrategy, "utf8"))
      : undefined,
    idBase: options.idBase,
    releaseId: options.releaseId,
    urlPrefix: options.urlPrefix,
    startDate: options.startDate,
    endDate: options.endDate,
    defaultTransferTime: options.defaultTransferTime,
    license: options.license,
  });
  const connectionsFile = await mapper.convert(sourcePath, outputPath);

  if (options.stream) {
    for await (const chunk of fs.createReadStream(connectionsFile)) {
      if (!process.stdout.write(chunk)) await once(process.stdout, "drain");
    }
  } else {
    console.error(
      `Linked Connections successfully created at ${connectionsFile}`,
    );
  }
}

program.parseAsync().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
